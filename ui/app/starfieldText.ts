/** Outside the Dynatrace shell (tests, a bare dev page) the preference call can throw: English then. */
const userLanguage = () => {
  try {
    return getLanguage();
  } catch {
    return "en";
  }
};

export const starfieldText = (): StarfieldText => (userLanguage().toLowerCase().startsWith("ko") ? ko : en);
